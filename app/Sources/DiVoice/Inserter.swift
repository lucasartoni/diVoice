import AppKit
import Carbon.HIToolbox
import DiVoiceCore

/// Inserts the text into the active app: pasteboard + synthetic Cmd+V.
///
/// The text goes onto the pasteboard through a "lazy" provider: the callback fires when
/// the target app actually reads the pasteboard, and that is the instant the text is
/// inserted. After the read, the original pasteboard contents are restored. If nobody reads
/// within one second, the text stays on the pasteboard for a manual paste.
final class Inserter: NSObject, NSPasteboardItemDataProvider {
  struct Outcome {
    var pastePostedNs: UInt64?
    var insertedNs: UInt64?
    /// The text stayed on the pasteboard: the user must press ⌘V.
    var manual: Bool
  }

  private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

  private struct Pending {
    let text: String
    let changeCount: Int
    let snapshot: Snapshot?
    let postedNs: UInt64
    let completion: (Outcome) -> Void
    var timer: Timer?
  }

  static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
  private static let maxSnapshotBytes = 50 * 1024 * 1024

  var restoreClipboard = true
  private let pasteboard = NSPasteboard.general
  private var pending: Pending?
  private var lastText = ""

  func insert(_ text: String, secureInput: Bool, completion: @escaping (Outcome) -> Void) {
    if pending != nil { giveUp() }
    lastText = text
    if secureInput {
      // Protected field (password): no automatic paste.
      copyForManualPaste(text)
      completion(Outcome(pastePostedNs: nil, insertedNs: nil, manual: true))
      return
    }

    let snapshot = restoreClipboard ? takeSnapshot() : nil
    pasteboard.clearContents()
    let item = NSPasteboardItem()
    item.setDataProvider(self, forTypes: [.string])
    // Well-behaved clipboard managers ignore content marked this way.
    item.setData(Data(), forType: Self.transientType)
    item.setData(Data(), forType: Self.concealedType)
    item.setData(Data(), forType: Self.autoGeneratedType)
    pasteboard.writeObjects([item])

    postCommandV()
    var entry = Pending(
      text: text,
      changeCount: pasteboard.changeCount,
      snapshot: snapshot,
      postedNs: MonotonicClock.nowNs(),
      completion: completion
    )
    entry.timer = Timer.scheduledTimer(withTimeInterval: 1.0, repeats: false) { [weak self] _ in self?.giveUp() }
    pending = entry
  }

  // MARK: NSPasteboardItemDataProvider

  func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
    guard let entry = pending else {
      item.setString(lastText, forType: type)
      return
    }
    item.setString(entry.text, forType: type)
    let readNs = MonotonicClock.nowNs()
    entry.timer?.invalidate()
    pending = nil
    // Give the app time to use the text before putting the original pasteboard back.
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { [weak self] in
      self?.restore(entry.snapshot, text: entry.text, ifChangeCount: entry.changeCount)
    }
    entry.completion(Outcome(pastePostedNs: entry.postedNs, insertedNs: readNs, manual: false))
  }

  func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {}

  // MARK: Private

  private func giveUp() {
    guard let entry = pending else { return }
    entry.timer?.invalidate()
    pending = nil
    copyForManualPaste(entry.text)
    entry.completion(Outcome(pastePostedNs: entry.postedNs, insertedNs: nil, manual: true))
  }

  private func copyForManualPaste(_ text: String) {
    pasteboard.clearContents()
    pasteboard.setString(text, forType: .string)
  }

  private func restore(_ snapshot: Snapshot?, text: String, ifChangeCount changeCount: Int) {
    // Someone else wrote to the pasteboard in the meantime: leave everything alone.
    guard pasteboard.changeCount == changeCount else { return }
    guard let snapshot else {
      // No restore: the provider is replaced with the actual text.
      copyForManualPaste(text)
      return
    }
    pasteboard.clearContents()
    let items = snapshot.map { pairs -> NSPasteboardItem in
      let item = NSPasteboardItem()
      for (type, data) in pairs { item.setData(data, forType: type) }
      return item
    }
    if !items.isEmpty { pasteboard.writeObjects(items) }
  }

  private func takeSnapshot() -> Snapshot? {
    var total = 0
    var snapshot: Snapshot = []
    for item in pasteboard.pasteboardItems ?? [] {
      var pairs: [(NSPasteboard.PasteboardType, Data)] = []
      for type in item.types {
        guard let data = item.data(forType: type) else { continue }
        total += data.count
        if total > Self.maxSnapshotBytes { return nil }
        pairs.append((type, data))
      }
      snapshot.append(pairs)
    }
    return snapshot
  }

  private func postCommandV() {
    let source = CGEventSource(stateID: .combinedSessionState)
    let key = KeyboardLayout.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
    for isDown in [true, false] {
      guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: isDown) else { continue }
      event.flags = .maskCommand
      event.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
      event.post(tap: .cghidEventTap)
    }
  }
}

/// Finds the key that produces a character in the active keyboard layout.
enum KeyboardLayout {
  static func keyCode(for character: Character) -> CGKeyCode? {
    guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
          let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
    else { return nil }
    let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
    return data.withUnsafeBytes { buffer -> CGKeyCode? in
      guard let layout = buffer.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
      for code in 0 ..< 128 {
        var deadKeyState: UInt32 = 0
        var length = 0
        var chars = [UniChar](repeating: 0, count: 4)
        let status = UCKeyTranslate(
          layout, UInt16(code), UInt16(kUCKeyActionDisplay), 0, UInt32(LMGetKbdType()),
          OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeyState, chars.count, &length, &chars
        )
        if status == noErr, length == 1, let scalar = UnicodeScalar(chars[0]), Character(scalar) == character {
          return CGKeyCode(code)
        }
      }
      return nil
    }
  }
}
